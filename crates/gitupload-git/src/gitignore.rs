#![forbid(unsafe_code)]
//! Built-in declarative `.gitignore` generator supporting multi-language presets and security defaults.

use gitupload_core::errors::GitUploadResult;
use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};

/// Generates deduplicated `.gitignore` files from built-in presets with mandatory secret protection.
pub struct GitignoreGenerator;

impl GitignoreGenerator {
    /// Lists supported built-in template identifiers.
    pub fn available_templates() -> &'static [&'static str] {
        &[
            "rust", "java", "maven", "gradle", "node", "python", "go", "windows", "macos",
        ]
    }

    /// Generates deduplicated `.gitignore` content combining `tags` plus mandatory security rules.
    pub fn render(tags: &[&str]) -> String {
        let mut lines = BTreeSet::new();
        for pat in [".env", ".env.*", "*.key", "*.pem", "id_rsa", "secrets.json"] {
            lines.insert(pat);
        }

        for tag in tags {
            for pat in rules_for_tag(tag) {
                lines.insert(*pat);
            }
        }

        let mut body = String::from("# Generated by GitUpload Declarative .gitignore Engine\n");
        for pat in lines {
            body.push_str(pat);
            body.push('\n');
        }
        body
    }

    /// Writes the rendered `.gitignore` directly into `<repo_root>/.gitignore`.
    pub fn write_to_repo(repo_root: &Path, tags: &[&str]) -> GitUploadResult<PathBuf> {
        let path = repo_root.join(".gitignore");
        let content = Self::render(tags);
        fs::write(&path, content)?;
        Ok(path)
    }
}

fn rules_for_tag(tag: &str) -> &'static [&'static str] {
    match tag.trim().to_ascii_lowercase().as_str() {
        "rust" => &["target/", "**/*.rs.bk", "Cargo.lock"],
        "java" => &["*.class", "*.jar", "*.war", "out/", ".idea/"],
        "maven" => &["target/", "pom.xml.tag", "pom.xml.releaseBackup"],
        "gradle" => &[".gradle/", "build/"],
        "node" | "react" | "typescript" => &["node_modules/", "dist/", ".vite/", "npm-debug.log*"],
        "python" => &[
            "__pycache__/",
            "*.py[cod]",
            ".venv/",
            "venv/",
            ".pytest_cache/",
        ],
        "go" => &["*.exe", "*.test", "*.out", "vendor/"],
        "windows" => &["Thumbs.db", "Desktop.ini", "*.lnk"],
        "macos" => &[".DS_Store", ".AppleDouble", ".LSOverride"],
        _ => &[],
    }
}
